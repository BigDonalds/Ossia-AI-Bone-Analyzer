/// Builds the same report the Ossia server sends, from the on-device model's
/// probabilities. A line-by-line port of the Python pipeline:
///
/// * `inference/analyzer.py`: `analyze_image`, `head_probabilities`,
///   `clarity`, `combine_photos`, `animal_taxa_probs`, `animal_answer`,
///   `_length_block`, `_widths_block`, `analyze_multiple_images`
/// * `inference/length_check.py`: `rerank` and its explanations
/// * `server.py`: `ModelService.analyze`, which tidies the report
///
/// The phone asks for a length only, never widths or a shape, so the parts of
/// those files that use them reduce to what they do without them.
///
/// Change it together with those files. test/on_device_report_test.dart checks
/// it against reports the Python code wrote for the same probabilities
/// (regenerated by `scripts/export_mobile.py`).
library;

import 'dart:math' as math;

import 'model_spec.dart';

/// One photo's calibrated probabilities from the exported model, by output
/// name, each list in the label order of [ModelSpec].
typedef HeadProbabilities = Map<String, List<double>>;

/// A length check's outcome: the probabilities after it and its JSON report.
typedef Reranked = ({
  List<double> species,
  List<double> boneType,
  List<double> animal,
  Map<String, dynamic> report,
});

class ReportBuilder {
  ReportBuilder(this.spec, this.lengths);

  final ModelSpec spec;
  final LengthTable lengths;

  LengthCheckSettings get _k => spec.lengthCheck;
  late final int _human = spec.species.indexOf('human');
  late final int _nonHuman = spec.species.indexOf('non_human');

  // ── server.py ─────────────────────────────────────────────────────────────

  /// The report for one or more photos of the same bone, shaped exactly like
  /// the server's `/analyze` answer. [names] label the photos in multi-photo
  /// reports; [lengthCm] is the user's measurement.
  Map<String, dynamic> report(
    List<HeadProbabilities> photos,
    List<String> names,
    double? lengthCm,
  ) {
    final Map<String, dynamic> report = photos.length == 1
        ? analyzeImage(photos.single, names.single, lengthCm)
        : analyzeMultipleImages(photos, names, lengthCm);

    final Map<String, dynamic> p1 =
        report['phase1_bone_detection'] as Map<String, dynamic>;
    p1.remove('image_path');
    final bool present = p1['final_verdict'] as bool;

    // Reference length range for the identified bone; nothing when there is
    // no bone or no range.
    final Map<String, dynamic> length =
        (report.remove('bone_length') as Map<String, dynamic>?) ??
            <String, dynamic>{};
    if (present && length['available'] == true) {
      report['bone_length'] = <String, dynamic>{
        'min_cm': _round1(length['min_cm'] as double),
        'max_cm': _round1(length['max_cm'] as double),
        'user_length_cm': lengthCm,
        'range_source': length['range_source'],
        'reference_for': length['reference_for'],
      };
    }

    report.putIfAbsent('num_images_analyzed', () => photos.length);
    final Map<String, dynamic> phase9 = report.putIfAbsent(
        'phase9_multi_image', () => <String, dynamic>{}) as Map<String, dynamic>;
    phase9.putIfAbsent('num_angles', () => photos.length);
    phase9['user_length_cm'] = lengthCm;
    return report;
  }

  // ── analyzer.py ───────────────────────────────────────────────────────────

  static Map<String, dynamic> _unavailablePhases() => <String, dynamic>{
        'phase2_species': <String, dynamic>{
          'species': 'unknown', 'confidence': 0.0, 'available': false,
        },
        'phase3_bone_type': <String, dynamic>{
          'predictions': <dynamic>[], 'available': false,
        },
        'phase4_bone_part': <String, dynamic>{'part': 'unknown', 'available': false},
        'phase5_completeness': <String, dynamic>{'status': 'unknown', 'available': false},
        'phase6_damage': <String, dynamic>{
          'fracture': 0.0, 'cut_marks': 0.0, 'burn_signs': 0.0, 'available': false,
        },
        'phase7_species_detail': <String, dynamic>{'species': 'unknown', 'available': false},
        'phase8_biological_profile': <String, dynamic>{
          'age_group': 'unknown', 'sex': 'unknown', 'available': false,
        },
        'bone_length': <String, dynamic>{'available': false},
      };

  /// `BoneAnalyzer.analyze_image`: one photo's phase report.
  Map<String, dynamic> analyzeImage(
    HeadProbabilities p,
    String imagePath,
    double? userLength,
  ) =>
      _analyze(p, imagePath, userLength).$1;

  /// `BoneAnalyzer._analyze`: the report, plus the probabilities it was built
  /// from (after the length check), or null when no bone was found.
  (Map<String, dynamic>, HeadProbabilities?) _analyze(
    HeadProbabilities p,
    String imagePath,
    double? userLength,
  ) {
    // Phase 1: bone detection
    final double boneConf = p['bone_detection']![0];
    final bool present = boneConf > 0.5;
    final Map<String, dynamic> results = <String, dynamic>{
      'phase1_bone_detection': <String, dynamic>{
        'bone_present': present,
        'confidence': boneConf,
        'final_verdict': present,
        'final_confidence': boneConf,
        'image_path': imagePath,
      },
    };
    if (!present) {
      results.addAll(_unavailablePhases());
      results['length_check'] = <String, dynamic>{
        'applied': false,
        'changed': false,
        'user_length_cm': userLength,
        'reason': "No bone was found, so the length wasn't used.",
      };
      results['shape_hint'] = _noShape();
      return (results, null);
    }

    final HeadProbabilities probs = headProbabilities(p);

    // No shape is picked on the phone, so shape_hint.apply_shape changes nothing
    final String top = spec.boneTypes[_argmax(probs['bone_type']!)];
    results['shape_hint'] = <String, dynamic>{
      ..._noShape(),
      'image_only': top,
      'with_shape': top,
    };

    // Length check: weigh species / bone type / taxon by the user's measurement
    final Reranked checked = rerank(
        probs['species']!,
        probs['bone_type']!,
        probs['animal']!,
        userLength,
        spec.parts[_argmax(probs['part']!)],
        spec.completeness[_argmax(probs['completeness']!)]);
    if (spec.useLengthRerank) {
      probs['species'] = checked.species;
      probs['bone_type'] = checked.boneType;
      probs['animal'] = checked.animal;
    }
    results['length_check'] = checked.report;
    results.addAll(_phases(probs));
    return (results, probs);
  }

  static Map<String, dynamic> _noShape() =>
      <String, dynamic>{'applied': false, 'changed': false, 'shape': null};

  /// One photo's outputs as the lists the report is built from: species,
  /// bone type, animal taxa ([ModelSpec.animalTaxa]), part, completeness,
  /// damage (each its own yes/no), age group and sex.
  HeadProbabilities headProbabilities(HeadProbabilities p) => <String, List<double>>{
        'species': p['species']!,
        'bone_type': p['bone_type']!,
        'animal': animalTaxaProbs(p),
        'part': p['bone_part']!,
        'completeness': p['completeness']!,
        'damage': p['damage']!,
        'age': p['age_group']!,
        'sex': p['sex']!,
      };

  /// How clear one photo's answer is for a head: 1 when it is certain, 0 when
  /// every option is equally likely (one minus the normalised entropy), plus a
  /// floor so every photo counts.
  static double clarity(List<double> probs) {
    double entropy = 0.0;
    for (final double p in probs) {
      if (p > 0) entropy -= p * math.log(p);
    }
    return 0.1 + 1 - entropy / math.log(probs.length);
  }

  /// Head by head, the average of several photos' probabilities, a clear
  /// photo counting more than a vague one. Damage is a plain mean.
  static HeadProbabilities combinePhotos(List<HeadProbabilities> photos) {
    final HeadProbabilities combined = <String, List<double>>{};
    for (final String head in photos.first.keys) {
      final List<List<double>> rows = <List<double>>[
        for (final HeadProbabilities p in photos) p[head]!,
      ];
      final List<double> weights = <double>[
        for (final List<double> r in rows) head == 'damage' ? 1.0 : clarity(r),
      ];
      final double total = weights.fold(0.0, (double a, double b) => a + b);
      combined[head] = <double>[
        for (int i = 0; i < rows.first.length; i++)
          _sumOf(rows.length, (int k) => weights[k] * rows[k][i]) / total,
      ];
    }
    return combined;
  }

  /// `BoneAnalyzer._phases`: phases 2-8 and the reference blocks, from one
  /// photo's probabilities or several photos' combined ones.
  Map<String, dynamic> _phases(HeadProbabilities probs) {
    final Map<String, dynamic> results = <String, dynamic>{};
    final int partIdx = _argmax(probs['part']!);
    final int compIdx = _argmax(probs['completeness']!);

    // Phase 2: species
    final List<double> speciesProbs = probs['species']!;
    final int speciesIdx = _argmax(speciesProbs);
    results['phase2_species'] = <String, dynamic>{
      'species': spec.species[speciesIdx],
      'confidence': speciesProbs[speciesIdx],
      'available': true,
    };

    // Phase 3: bone type (top 3)
    final List<double> boneTypeProbs = probs['bone_type']!;
    final List<int> top3 = _ranked(boneTypeProbs).take(3).toList();
    results['phase3_bone_type'] = <String, dynamic>{
      'predictions': <Map<String, dynamic>>[
        for (final int i in top3)
          <String, dynamic>{
            'bone_type': spec.boneTypes[i],
            'confidence': boneTypeProbs[i],
          },
      ],
      'available': true,
    };

    // Phases 4-5: bone part and completeness
    results['phase4_bone_part'] = <String, dynamic>{
      'part': spec.parts[partIdx],
      'confidence': probs['part']![partIdx],
      'available': true,
    };
    results['phase5_completeness'] = <String, dynamic>{
      'status': spec.completeness[compIdx],
      'confidence': probs['completeness']![compIdx],
      'available': true,
    };

    // Phase 6: damage (multi-label)
    final List<double> damage = probs['damage']!;
    results['phase6_damage'] = <String, dynamic>{
      'fracture': damage[0],
      'cut_marks': damage[1],
      'burn_signs': damage[2],
      'available': true,
    };

    // Phase 7: animal class, and family group when the bone shows it
    final bool isHuman = spec.species[speciesIdx] == 'human';
    final Map<String, dynamic> animal =
        animalAnswer(probs['animal']!, spec.boneTypes[top3[0]], spec.parts[partIdx]);
    results['phase7_species_detail'] = <String, dynamic>{
      ...animal,
      'available': true,
      'applicable': !isHuman,
    };

    // Phase 8: biological profile (age and sex), human only
    if (isHuman) {
      final List<double> ageProbs = probs['age']!;
      final List<double> sexProbs = probs['sex']!;
      final int ageIdx = _argmax(ageProbs);
      final int sexIdx = _argmax(sexProbs);
      results['phase8_biological_profile'] = <String, dynamic>{
        'age_group': spec.ageGroups[ageIdx],
        'age_confidence': ageProbs[ageIdx],
        'sex': spec.sexes[sexIdx],
        'sex_confidence': sexProbs[sexIdx],
        'available': true,
        'applicable': true,
      };
    } else {
      results['phase8_biological_profile'] = <String, dynamic>{
        'available': true,
        'applicable': false,
        'note': 'Non-human bone',
      };
    }

    final String taxon = isHuman
        ? 'human'
        : (animal['family'] as String?) ?? animal['class'] as String;
    results['bone_length'] = _lengthBlock(taxon, spec.boneTypes[top3[0]]);
    results['bone_widths'] = _widthsBlock(taxon, spec.boneTypes[top3[0]]);
    // head_sex.sex_from_head needs a measured head diameter, which the phone
    // doesn't ask for
    results['head_sex_hint'] = <String, dynamic>{'available': false};
    return results;
  }

  /// Probabilities over [ModelSpec.animalTaxa]: p(mammal) x p(family) for the
  /// mammal family groups, then the class probability for birds and reptiles.
  List<double> animalTaxaProbs(HeadProbabilities p) {
    final Map<String, double> pClass = <String, double>{
      for (int i = 0; i < spec.animalClasses.length; i++)
        spec.animalClasses[i]: p['animal_class']![i],
    };
    return <double>[
      for (final double f in p['animal_family']!) pClass['mammal']! * f,
      for (final String c in spec.animalTaxa.skip(spec.mammalFamilies.length))
        pClass[c]!,
    ];
  }

  /// Whether a photo of this bone can show the animal's family
  /// (`taxonomy.family_visible`).
  bool familyVisible(String boneType, String part) {
    if (!spec.familyBoneTypes.contains(boneType)) return false;
    return const <String>{'skull', 'cranium', 'mandible'}.contains(boneType) ||
        !const <String>{'fragment', 'shaft'}.contains(part);
  }

  /// The phase 7 block: the class always; the family only for a mammal whose
  /// bone shows it, and named only when it holds at least
  /// [ModelSpec.familyMinConfidence] of the mammal probability.
  Map<String, dynamic> animalAnswer(
    List<double> taxaProbs,
    String boneType,
    String part,
  ) {
    final int nFamilies = spec.mammalFamilies.length;
    final List<double> families = taxaProbs.sublist(0, nFamilies);
    final Map<String, double> classProbs = <String, double>{
      'mammal': families.fold(0.0, (double a, double b) => a + b),
      for (int i = nFamilies; i < taxaProbs.length; i++)
        spec.animalTaxa[i]: taxaProbs[i],
    };
    final String animalClass = _firstMax(classProbs);
    String? family;
    double familyConf = 0.0;
    if (animalClass == 'mammal' &&
        familyVisible(boneType, part) &&
        classProbs['mammal']! > 0) {
      final int best = _argmax(families);
      family = spec.mammalFamilies[best];
      familyConf = families[best] / classProbs['mammal']!;
    }
    final String? named = family != null &&
            family != 'other_mammal' &&
            familyConf >= spec.familyMinConfidence
        ? family
        : null;
    return <String, dynamic>{
      'species': named ?? animalClass,
      'confidence': named != null
          ? taxaProbs[spec.animalTaxa.indexOf(named)]
          : classProbs[animalClass],
      'class': animalClass,
      'class_confidence': classProbs[animalClass],
      'family': family,
      'family_confidence': familyConf,
    };
  }

  /// Reference length range for the identified bone, when the table has one.
  Map<String, dynamic> _lengthBlock(String taxon, String boneType) {
    final LengthRange? entry = lengths.range(taxon, boneType);
    if (entry == null || entry.upperBoundOnly) return <String, dynamic>{'available': false};
    final String measured = (entry.measuredOn ?? '').isNotEmpty
        ? ' (measured on ${entry.measuredOn})'
        : '';
    return <String, dynamic>{
      'min_cm': entry.minCm,
      'max_cm': entry.maxCm,
      'range_source': 'reference',
      'reference_for': displayName(taxon, boneType) + measured,
      'available': true,
    };
  }

  /// Reference width ranges for the identified bone, per measurement the
  /// table has.
  Map<String, dynamic> _widthsBlock(String taxon, String boneType) {
    final Map<String, dynamic> widths = <String, dynamic>{};
    for (final String m in LengthTable.measurements.keys) {
      final LengthRange? entry =
          m == 'length_cm' ? null : lengths.range(taxon, boneType, m);
      if (entry != null) {
        widths[m] = <String, dynamic>{
          'min_cm': entry.minCm,
          'max_cm': entry.maxCm,
          'reference_for': displayName(taxon, boneType),
        };
      }
    }
    return <String, dynamic>{'available': widths.isNotEmpty, ...widths};
  }

  /// `BoneAnalyzer.analyze_multiple_images`: the photos that show a bone are
  /// combined head by head ([combinePhotos]) and the report is built from
  /// that, as for a single photo; a photo without a bone doesn't water the
  /// answer down.
  Map<String, dynamic> analyzeMultipleImages(
    List<HeadProbabilities> photos,
    List<String> names,
    double? userLength,
  ) {
    final List<(Map<String, dynamic>, HeadProbabilities?)> analyzed =
        <(Map<String, dynamic>, HeadProbabilities?)>[
      for (int i = 0; i < photos.length; i++) _analyze(photos[i], names[i], userLength),
    ];
    final int n = analyzed.length;

    // A bone is there if any photo shows one, as surely as the surest photo says so
    final List<Map<String, dynamic>> detections = <Map<String, dynamic>>[
      for (final (Map<String, dynamic>, HeadProbabilities?) r in analyzed)
        r.$1['phase1_bone_detection'] as Map<String, dynamic>,
    ];
    final List<HeadProbabilities> bonePhotos = <HeadProbabilities>[
      for (final (Map<String, dynamic>, HeadProbabilities?) r in analyzed)
        if (r.$2 != null) r.$2!,
    ];
    final double best = detections
        .map((Map<String, dynamic> d) => d['final_confidence'] as double)
        .reduce(math.max);
    final Map<String, dynamic> report = <String, dynamic>{
      'phase1_bone_detection': <String, dynamic>{
        'bone_present': bonePhotos.isNotEmpty,
        'confidence': best,
        'final_verdict': bonePhotos.isNotEmpty,
        'final_confidence': best,
        'per_image': <Map<String, dynamic>>[
          for (final Map<String, dynamic> d in detections)
            <String, dynamic>{
              'image': _fileName(d['image_path'] as String),
              'final_verdict': d['final_verdict'],
              'final_confidence': d['final_confidence'],
            },
        ],
      },
    };
    report.addAll(bonePhotos.isNotEmpty
        ? _phases(combinePhotos(bonePhotos))
        : _unavailablePhases());
    (report['bone_length'] as Map<String, dynamic>)['user_length_cm'] = userLength;

    // Each photo was re-ranked with the same length before they were combined
    final List<Map<String, dynamic>> checks = <Map<String, dynamic>>[
      for (final (Map<String, dynamic>, HeadProbabilities?) r in analyzed)
        r.$1['length_check'] as Map<String, dynamic>,
    ];
    final List<Map<String, dynamic>> shapes = <Map<String, dynamic>>[
      for (final (Map<String, dynamic>, HeadProbabilities?) r in analyzed)
        r.$1['shape_hint'] as Map<String, dynamic>,
    ];
    report['length_check'] = <String, dynamic>{
      'applied': checks.any((Map<String, dynamic> c) => c['applied'] == true),
      'changed': checks.any((Map<String, dynamic> c) => c['changed'] == true),
      'user_length_cm': userLength,
      'measurements': _measurements(userLength),
      'per_image': checks,
    };
    report['shape_hint'] = <String, dynamic>{
      'applied': shapes.any((Map<String, dynamic> h) => h['applied'] == true),
      'changed': shapes.any((Map<String, dynamic> h) => h['changed'] == true),
      'shape': null,
      'per_image': shapes,
    };
    report['phase9_multi_image'] = <String, dynamic>{
      'num_angles': n,
      'photos_with_bone': bonePhotos.length,
      'user_length_cm': userLength,
    };
    report['num_images_analyzed'] = n;
    return report;
  }

  /// The measurements given, by name (only ever a length on the phone).
  static Map<String, dynamic> _measurements(double? lengthCm) =>
      <String, dynamic>{'length_cm': ?lengthCm};


  // ── length_check.py ───────────────────────────────────────────────────────

  /// Where a length falls against a range: (fit, side). Fit is 1 inside the
  /// range and decays outside; side is 'inside', 'above' or 'below'.
  (double, String) lengthFit(double lengthCm, double minCm, double maxCm) {
    final double slack = math.max(_k.slackCm, _k.slackFraction * lengthCm);
    if (lengthCm > maxCm + slack) {
      final double over = (lengthCm - maxCm - slack) / maxCm / _k.toleranceAbove;
      return (math.exp(-(over * over)), 'above');
    }
    if (lengthCm < minCm - slack) {
      final double under = (minCm - slack - lengthCm) / minCm / _k.toleranceBelow;
      return (math.exp(-(under * under)), 'below');
    }
    return (1.0, 'inside');
  }

  /// Weight applied to a candidate's probability, plus its fit and side
  /// (both null when the table has no range for it, or the length is under an
  /// upper-bound-only entry).
  (double, double?, String?) candidateWeight(double lengthCm, LengthRange? entry) {
    if (entry == null) return (1.0, null, null);
    final (double fit, String side) = lengthFit(lengthCm, entry.minCm, entry.maxCm);
    if (entry.upperBoundOnly && side != 'above') return (1.0, null, null);
    final double floor = side == 'above' ? _k.floorAbove : _k.floorBelow;
    final double weight = floor + (1 - floor) * fit;
    return (1 - _k.confidencePull[entry.confidence]! * (1 - weight), fit, side);
  }

  String displayName(String taxon, String boneType) {
    final String who = _k.unnamedTaxa.contains(taxon)
        ? 'unidentified animal'
        : (_k.shownAs[taxon] ?? taxon);
    final String bone =
        boneType.replaceAll('_', ' ').replaceAll('vertebrae', 'vertebra');
    return '$who $bone';
  }

  /// The headline from the top classes: taxon, bone type and their confidence.
  Map<String, dynamic> _answer(
      List<double> speciesProbs, List<double> boneTypeProbs, List<double> animalProbs) {
    final int species = _argmax(speciesProbs);
    final int boneType = _argmax(boneTypeProbs);
    final int animal = _argmax(animalProbs);
    return <String, dynamic>{
      'taxon': species == _human ? 'human' : spec.animalTaxa[animal],
      'bone_type': spec.boneTypes[boneType],
      'species_confidence': speciesProbs[species],
      'bone_type_confidence': boneTypeProbs[boneType],
    };
  }

  /// Weighs the species, bone type and taxon probabilities by a measured
  /// length (`length_check.rerank`). Returns the inputs unchanged when the
  /// check doesn't apply.
  Reranked rerank(
    List<double> speciesProbs,
    List<double> boneTypeProbs,
    List<double> animalProbs,
    double? lengthCm,
    String? part,
    String? completeness,
  ) {
    final Map<String, dynamic> imageAnswer =
        _answer(speciesProbs, boneTypeProbs, animalProbs);
    final Map<String, dynamic> report = <String, dynamic>{
      'applied': false,
      'changed': false,
      'user_length_cm': lengthCm,
      'measurements': _measurements(lengthCm),
      'image_only': imageAnswer,
      'with_length': imageAnswer,
    };
    final Reranked unchanged = (
      species: speciesProbs,
      boneType: boneTypeProbs,
      animal: animalProbs,
      report: report,
    );

    if (lengthCm == null) {
      report['reason'] = 'No length was entered.';
      return unchanged;
    }
    if (part != 'complete' || completeness != 'complete') {
      final String shown = _k.partShownAs[part != 'complete' ? part : completeness] ??
          'only part of a bone';
      report['reason'] =
          "This looks like $shown, so its length can't be compared with whole bones.";
      return unchanged;
    }
    report['measurements_used'] = <String>['length_cm'];

    final List<_Candidate> candidates = <_Candidate>[];
    for (int t = 0; t < boneTypeProbs.length; t++) {
      final List<(String, double)> taxa = <(String, double)>[
        ('human', speciesProbs[_human]),
        for (int i = 0; i < spec.animalTaxa.length; i++)
          (spec.animalTaxa[i], speciesProbs[_nonHuman] * animalProbs[i]),
      ];
      for (final (String taxon, double pTaxon) in taxa) {
        final LengthRange? entry = lengths.range(taxon, spec.boneTypes[t]);
        final (double weight, double? _, String? side) = candidateWeight(lengthCm, entry);
        candidates.add(_Candidate(
          taxon: taxon,
          boneType: spec.boneTypes[t],
          // Under an upper bound: as good as no entry
          entry: side == null ? null : entry,
          prior: pTaxon * boneTypeProbs[t],
          weight: weight,
          side: side,
        ));
      }
    }

    final double checkable = candidates
        .where((_Candidate c) => c.entry != null)
        .fold(0.0, (double s, _Candidate c) => s + c.prior);
    if (checkable < _k.minCheckableMass) {
      final String names = _stableSorted(candidates, (_Candidate c) => -c.prior)
          .take(2)
          .map((_Candidate c) => _a(displayName(c.taxon, c.boneType)))
          .join(' or ');
      report['reason'] = "We don't have usual lengths for $names, so the length wasn't used.";
      return unchanged;
    }

    // Probability moves only between the candidates the length could check;
    // the others keep exactly what the photo gave them.
    final double scale = checkable /
        candidates
            .where((_Candidate c) => c.entry != null)
            .fold<double>(0.0, (double s, _Candidate c) => s + c.prior * c.weight);
    for (final _Candidate c in candidates) {
      c.posterior = c.entry != null ? c.prior * c.weight * scale : c.prior;
    }

    final List<double> newSpecies = List<double>.filled(speciesProbs.length, 0.0);
    final List<double> newBoneType = List<double>.filled(boneTypeProbs.length, 0.0);
    List<double> newAnimal = List<double>.filled(animalProbs.length, 0.0);
    for (final _Candidate c in candidates) {
      newBoneType[spec.boneTypes.indexOf(c.boneType)] += c.posterior;
      if (c.taxon == 'human') {
        newSpecies[_human] += c.posterior;
      } else {
        newSpecies[_nonHuman] += c.posterior;
        newAnimal[spec.animalTaxa.indexOf(c.taxon)] += c.posterior;
      }
    }
    if (newSpecies[_nonHuman] > 0) {
      final double nonHuman = newSpecies[_nonHuman];
      newAnimal = <double>[for (final double p in newAnimal) p / nonHuman];
    } else {
      newAnimal = animalProbs;
    }

    final Map<String, dynamic> finalAnswer = _answer(newSpecies, newBoneType, newAnimal);
    final bool changed = finalAnswer['taxon'] != imageAnswer['taxon'] ||
        finalAnswer['bone_type'] != imageAnswer['bone_type'];
    report['applied'] = true;
    report['candidates'] = <Map<String, dynamic>>[
      for (final _Candidate c
          in _stableSorted(candidates, (_Candidate c) => -c.posterior)
              .take(_k.candidatesReported))
        <String, dynamic>{
          'taxon': c.taxon,
          'bone_type': c.boneType,
          'reference_cm': _referenceCm(c.taxon, c.boneType),
          'length_fit': c.side ?? 'no reference',
          'reference_widths_cm': <String, dynamic>{},
          'fits': <String, dynamic>{'length_cm': ?c.side},
          'image_probability': c.prior,
          'length_weighted_probability': c.posterior,
        },
    ];

    // Only let the length replace the answer with one it actually fits (or
    // can't check). Swapping between two candidates it contradicts would be
    // guesswork, especially for juveniles, whose bones are all short.
    final (String _, String? afterSide) = _describe(lengthCm, finalAnswer);
    if (changed && (afterSide == 'above' || afterSide == 'below')) {
      report['reason'] = _explainNoFit(lengthCm, imageAnswer, finalAnswer);
      return unchanged;
    }

    report['changed'] = changed;
    report['with_length'] = finalAnswer;
    report['reason'] = _explain(lengthCm, imageAnswer, finalAnswer, changed);
    return (
      species: newSpecies,
      boneType: newBoneType,
      animal: newAnimal,
      report: report,
    );
  }

  List<double>? _referenceCm(String taxon, String boneType) {
    final LengthRange? entry = lengths.range(taxon, boneType);
    return entry == null ? null : <double>[entry.minCm, entry.maxCm];
  }

  /// 'a human femur (usually 34.4–55 cm)' plus where the length falls.
  (String, String?) _describe(double lengthCm, Map<String, dynamic> a) {
    final String taxon = a['taxon'] as String;
    final String boneType = a['bone_type'] as String;
    final LengthRange? entry = lengths.range(taxon, boneType);
    final String name = _a(displayName(taxon, boneType));
    if (entry == null) return (name, null);
    final (double _, String side) = lengthFit(lengthCm, entry.minCm, entry.maxCm);
    if (entry.upperBoundOnly) {
      return side == 'above' ? ('$name (never over ${formatG(entry.maxCm)} cm)', side) : (name, null);
    }
    return ('$name (usually ${formatG(entry.minCm)}–${formatG(entry.maxCm)} cm)', side);
  }

  String _explainNoFit(
      double lengthCm, Map<String, dynamic> imageAnswer, Map<String, dynamic> best) {
    final (String before, String? _) = _describe(lengthCm, imageAnswer);
    final (String after, String? _) = _describe(lengthCm, best);
    return "${formatG(lengthCm)} cm doesn't fit $before or the next closest option, "
        "$after, so we kept the photo's answer. It could be from a young animal or "
        'person, or worth measuring again.';
  }

  String _explain(double lengthCm, Map<String, dynamic> imageAnswer,
      Map<String, dynamic> finalAnswer, bool changed) {
    final String length = '${formatG(lengthCm)} cm';
    final (String before, String? beforeSide) = _describe(lengthCm, imageAnswer);
    final (String after, String? afterSide) = _describe(lengthCm, finalAnswer);
    if (changed) {
      final String why = switch (beforeSide) {
        'above' => 'is too long for $before',
        'below' => 'is too short for $before',
        'inside' => 'fits $before, but ruling out other options shifted the answer',
        _ => "can't be checked against $before",
      };
      final String fits = afterSide == 'inside'
          ? 'it fits $after'
          : "$after can't be ruled out by length";
      return '$length $why, and $fits, so the length changed the answer.';
    }
    if (beforeSide == null) {
      return "We don't have a usual length for $before, so the length couldn't "
          'confirm it. It only helped weigh up the other options.';
    }
    if (beforeSide == 'inside') {
      return '$length is a normal length for $before, which backs up the answer.';
    }
    if (beforeSide == 'below') {
      return '$length is short for $before, but the photo still points to it. It '
          'could be from a young animal or person, or worth measuring again.';
    }
    return '$length is long for $before, but the photo still points to it. Worth '
        'measuring again.';
  }
}

class _Candidate {
  _Candidate({
    required this.taxon,
    required this.boneType,
    required this.entry,
    required this.prior,
    required this.weight,
    required this.side,
  });

  final String taxon;
  final String boneType;
  final LengthRange? entry;
  final double prior;
  final double weight;
  final String? side;
  double posterior = 0;
}

/// Python's `f'{x:g}'` for the lengths in explanations: six significant
/// digits without trailing zeros, so 45.0 reads "45" and 19.05 "19.05".
String formatG(double x) {
  String s = x.toStringAsPrecision(6);
  if (s.contains('e') || !s.contains('.')) return s;
  s = s.replaceFirst(RegExp(r'0+$'), '');
  return s.endsWith('.') ? s.substring(0, s.length - 1) : s;
}

double _round1(double x) => double.parse(x.toStringAsFixed(1));

/// 'a human femur', 'an equid (horse family) femur'.
String _a(String phrase) => '${'aeiou'.contains(phrase[0]) ? 'an' : 'a'} $phrase';

String _fileName(String path) => path.split(RegExp(r'[/\\]')).last;

/// f(0) + f(1) + ... + f(n - 1), added in that order like Python's sum().
double _sumOf(int n, double Function(int) f) {
  double total = 0.0;
  for (int i = 0; i < n; i++) {
    total += f(i);
  }
  return total;
}

/// Index of the largest value; the first one on a tie, like Python's max().
int _argmax(List<double> values) {
  int best = 0;
  for (int i = 1; i < values.length; i++) {
    if (values[i] > values[best]) best = i;
  }
  return best;
}

String _firstMax(Map<String, double> m) {
  String? best;
  for (final MapEntry<String, double> e in m.entries) {
    if (best == null || e.value > m[best]!) best = e.key;
  }
  return best!;
}

/// Indices from the largest value down; ties keep index order.
List<int> _ranked(List<double> values) => _stableSorted(
    List<int>.generate(values.length, (int i) => i), (int i) => -values[i]);

/// Sorted by [key] ascending; equal keys keep their order, like Python's sorted().
List<T> _stableSorted<T>(List<T> items, double Function(T) key) {
  final List<int> order = List<int>.generate(items.length, (int i) => i)
    ..sort((int a, int b) {
      final int c = key(items[a]).compareTo(key(items[b]));
      return c != 0 ? c : a.compareTo(b);
    });
  return <T>[for (final int i in order) items[i]];
}
